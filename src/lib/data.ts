export function nextReferralId(existing: Referral[]): string {
  const nums = existing.map((r) => {
    const m = r.id.match(/SR-(\d+)/);
    return m ? parseInt(m[1], 10) : 1000;
  });
  const next = Math.max(1041, ...nums) + 1;
  return `SR-${next}`;
}

export function freshnessLabel(provider: Provider): string {
  const mins = Math.round(
    (Date.now() - new Date(provider.lastConfirmedAt).getTime()) / 60000
  );
  if (provider.capacityStatus === "No current usable space") {
    return "No current usable space";
  }
  if (provider.capacityStatus === "Needs confirmation") {
    return "Confirm before referring";
  }
  if (mins < 60) return `Confirmed ${mins} minutes ago`;
  const hours = Math.round(mins / 60);
  return `Confirmed ${hours} hour${hours === 1 ? "" : "s"} ago`;
}

/** Emergency services use a short freshness window; routine services longer. */
export function recomputeCapacityStatus(provider: Provider): CapacityStatus {
  if (provider.temporaryClosure || provider.capacity <= 0) {
    return "No current usable space";
  }
  const emergency = provider.serviceTypes.some((s) =>
    ["Emergency shelter", "Safe parking", "Recuperative care"].includes(s)
  );
  const windowHours = emergency ? 12 : 48;
  const ageHours =
    (Date.now() - new Date(provider.lastConfirmedAt).getTime()) / 3600000;
  if (ageHours > windowHours) return "Needs confirmation";
  return "Confirmed recently";
}
